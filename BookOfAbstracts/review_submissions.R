programme_lines <- readLines("README.md", encoding = "UTF-8", warn = FALSE)
entries <- list()
for (line in programme_lines) {
  cells <- if (grepl("^\\s*\\|", line)) strsplit(line, "\\|")[[1]] else line
  for (cell in cells) {
    entry <- extract_programme_entry(cell)
    if (!is.null(entry)) entries[[length(entries) + 1L]] <- as.data.table(entry)
  }
}
programme <- unique(rbindlist(entries)[, key := normalize_title(title)], by = "key")
book_keys <- normalize_title(abstracts$TITLE)
# Resolve typographical title variants only; the original abstract remains intact.
missing_programme <- programme[!key %in% book_keys]
unscheduled_book <- abstracts[!book_keys %in% programme$key]
excluded <- submissions[STATUT == "Accepted" & !as.character(DOCID) %in% abstracts$DOCID,
                        .(DOCID, TYPDOC, TITLE)]
excluded[, REASON := ifelse(as.character(DOCID) %in% excluded_docids,
                            "Existing explicit exclusion; absent from programme",
                            "EMOS submission outside existing selected list; absent from programme")]
fwrite(excluded, "BookOfAbstracts/excluded_accepted.csv")
issues <- data.table(DOCID = character(), TITLE = character(), ISSUE = character(), DETAIL = character())
add_issue <- function(id, title, issue, detail) {
  issues <<- rbind(issues, data.table(DOCID = as.character(id), TITLE = title, ISSUE = issue, DETAIL = detail))
}
for (i in seq_len(nrow(missing_programme))) {
  add_issue("", missing_programme$title[i], "Programme entry missing from book", missing_programme$authors[i])
}
for (i in seq_len(nrow(unscheduled_book))) {
  add_issue(unscheduled_book$DOCID[i], unscheduled_book$TITLE[i], "Book entry not matched to programme", "Check title or inclusion")
}
for (i in seq_len(nrow(abstracts))) {
  a <- abstracts[i]
  for (field in c("TITLE", "Authors", "LABOS", "ABSTRACT")) {
    if (is.na(a[[field]]) || !nzchar(trimws(a[[field]]))) add_issue(a$DOCID, a$TITLE, "Missing field", field)
  }
  if (grepl("^invited-", a$DOCID)) next
  for (author in split_people(a$Authors)) {
    if (!grepl("\\([0-9]+\\)", author)) {
      add_issue(a$DOCID, a$TITLE, "Author affiliation reference missing", author)
    }
  }
  original <- clean_people(submissions[as.character(DOCID) == a$DOCID, AUTHORS])
  reference <- programme_authors(a$TITLE, "", programme_lookup)
  for (author in split_people(original)) {
    if (!any(vapply(split_people(reference), function(ref) any(person_match_keys(ref) %in% person_match_keys(author)), logical(1)))) {
      add_issue(a$DOCID, a$TITLE, "Submitted co-author absent from programme (retained in book)", author)
    }
  }
}
fwrite(issues, "BookOfAbstracts/review_issues.csv")
